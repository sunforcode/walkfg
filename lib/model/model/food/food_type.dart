/// 食物类型枚举
///
/// 用于区分不同的膳食类型
///
/// 在户外活动中，合理安排不同类型的膳食对于保持能量和营养平衡至关重要。
/// 这个枚举定义了五种基本的膳食类型：
/// - breakfast: 早餐，通常是一天中的第一餐，提供开始活动所需的能量
/// - lunch: 午餐，通常在活动中途食用，补充上午消耗的能量
/// - dinner: 晚餐，一天中的主要餐食，提供较多的营养和能量
/// - snack: 零食，在主餐之间食用，提供快速能量补充
/// - drink: 饮料，包括水和其他饮品，保持水分平衡

/// 食物类型
enum FoodType {
  /// 早餐
  breakfast,

  /// 午餐
  lunch,

  /// 晚餐
  dinner,

  /// 零食
  snack,

  /// 饮料
  drink
}
